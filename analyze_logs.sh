#!/bin/bash

LOG_FILE="access.log"

# генерируем случайный лог, если его нет
if [ ! -f "$LOG_FILE" ]; then
    echo "Генерация тестового файла $LOG_FILE (300 строк)..."
    for i in {1..300}; do
        # генерируем случайный IP
        IP="192.168.1.$((RANDOM % 255))"
        # Случайный метод (GET или POST)
        if [ $((RANDOM % 2)) -eq 0 ]; then METHOD="GET"; else METHOD="POST"; fi
        # Случайный код ответа (200, 401, 404, 500)
        CODES=("200" "200" "200" "401" "404" "500")
        CODE=${CODES[$((RANDOM % 6))]}
        
        # Записываем строку в формате из задания
        echo "$IP - - [15/Aug/2026:10:15:33] \"$METHOD /api/login HTTP/1.1\" $CODE" >> "$LOG_FILE"
    done
    echo "Файл создан."
    echo "-----------------------------"
fi

# общее количество запросов, считаем количество строк в фвйле
TOTAL=$(wc -l < "$LOG_FILE")
echo "Общее количество запросов: $TOTAL"

# топ-3 IP-адреса
# awk берет 1-й столбец (IP), sort сортирует, uniq -c считает повторы, sort -nr сортирует по убыванию, head -3 берет топ-3
echo "Топ-3 IP-адреса с наибольшим числом запросов:"
awk '{print $1}' "$LOG_FILE" | sort | uniq -c | sort -nr | head -n 3

# количество запросов с кодами 4xx и 5xx
# Используем awk с регулярным выражением: ищем 9-й столбец (код ответа), который начинается на 4 или 5
echo "Количество запросов с кодами 4xx и 5xx:"
awk '$NF ~ /^[45][0-9][0-9]$/ {count++} END {print count+0}' "$LOG_FILE"
